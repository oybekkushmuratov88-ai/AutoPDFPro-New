console.log('\n=== 9. Тросовые молниеотводы (Приложение 2, стр. 60) ===');
/* ================================================================== */
{
  near(cableCoefs('1e-2').k1, 1.2, 1e-12, 'прорыв 1e-2:  k1 = 1,2');
  near(cableCoefs('1e-2').k2, 1.0, 1e-12, 'прорыв 1e-2:  k2 = 1,0');
  near(cableCoefs('1e-3').k1, 0.6, 1e-12, 'прорыв 1e-3:  k1 = 0,6');
  near(cableCoefs('1e-3').k2, 1.3, 1e-12, 'прорыв 1e-3:  k2 = 1,3');

  near(cableTruncation(25, '1e-3'), 0, 1e-12, 'h = 25 м — усечения нет');
  near(cableTruncation(50, '1e-3'), 0.29 * 20 * 1.3, 1e-12, 'h = 50 м  Δh = 0,29(h−30)k2');
  near(cableTruncation(50, '1e-2'), 0.29 * 20 * 1.0, 1e-12, 'то же при k2 = 1,0');
  near(cableTruncation(150, '1e-2'), 0.2 * 150 * 1.0, 1e-12, 'h = 150 м  Δh = 0,2·h·k2');

  // П.2.1: h < 30 -> P не применяется
  near(cableZone(25, 10, '1e-3'), 0.6 * 15 / (1 + 10 / 25), 1e-9, 'П.2.1  h=25 hx=10  k1=0,6');
  near(cableZone(25, 10, '1e-2'), 1.2 * 15 / (1 + 10 / 25), 1e-9, 'П.2.1  тот же случай, k1=1,2');
  // П.2.2: 30…250 -> с коэффициентом P
  const P40 = 5.5 / Math.sqrt(40);
  near(cableZone(40, 10, '1e-2'), 1.2 * 30 / (1 + 10 / 40) * P40, 1e-9, 'П.2.2  h=40 hx=10  с P');
  // усечение
  near(cableZone(50, 45, '1e-3'), 0, 1e-12, 'h=50 hx=45: ha=5 < Δh=7,54 -> rx = 0');

  // провис троса
  const c: CableRod = { id: 'T', name: 'Трос-1', x1: 0, y1: 0, x2: 100, y2: 0, h: 30, sag: 4 };
  near(cableHeightAt(c, 0),   30, 1e-12, 'у опоры высота = h');
  near(cableHeightAt(c, 1),   30, 1e-12, 'у второй опоры высота = h');
  near(cableHeightAt(c, 0.5), 26, 1e-12, 'в середине пролёта h − стрела провиса');

  // покрытие: точка на оси троса в середине
  const cv = cableCoverage(50, 0, 10, c);
  is(cv.covered, true, 'точка под тросом защищена');
  // точка за пределами пролёта
  is(cableCoverage(-10, 0, 10, c).covered, false, 'точка за опорой не защищена');
  // точка сбоку дальше rx
  is(cableCoverage(50, 500, 10, c).covered, false, 'точка далеко сбоку не защищена');
}

