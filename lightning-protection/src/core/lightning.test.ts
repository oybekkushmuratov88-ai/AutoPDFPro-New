console.log('\n=== 7. Три молниеотвода — условие стр. 58 ===');
console.log('    "Д <= 8·ha  (h <= 30 м);   Д <= 8·ha·P  (30 < h < 250 м)"');
/* ================================================================== */
{
  const m: Method = 'RU';
  const mk = (n: string, x: number, y: number, h: number): Rod => ({ id: n, name: n, x, y, h });

  // равносторонний треугольник со стороной s: D = s/sqrt(3)*2 = 2s/sqrt(3)
  const s = 40, R = s / Math.sqrt(3);
  const A = mk('A', 0, R, 20), B = mk('B', -s / 2, -R / 2, 20), C = mk('C', s / 2, -R / 2, 20);
  const t = tripleZone(A, B, C, 6, m);
  near(t.D, 2 * R, 0.01, 'Д описанной окружности равностороннего треугольника');
  near(t.Dmax, 8 * (20 - 6), 0.01, 'Дmax = 8·ha  при h = 20 <= 30 (P = 1)');
  is(t.ok, true, 'Д = 46.2 <= Дmax = 112  — площадь защищена');

  // тот же треугольник, но уровень почти у вершины: ha мал -> условие не выполняется
  const t2 = tripleZone(A, B, C, 19.5, m);
  is(t2.ok, false, 'hx = 19.5: ha = 0.5, Дmax = 4 — условие не выполнено');

  // P входит в предел при h > 30
  const D2 = mk('D', 0, R, 40), E2 = mk('E', -s / 2, -R / 2, 40), F2 = mk('F', s / 2, -R / 2, 40);
  const t3 = tripleZone(D2, E2, F2, 6, m);
  near(t3.Dmax, 8 * (40 - 6) * coefP(40), 0.01, 'Дmax = 8·ha·P при h = 40 > 30');

  // вырожденный треугольник (три точки на прямой) — условие неприменимо
  const g1 = mk('G', 0, 0, 20), g2 = mk('H', 10, 0, 20), g3 = mk('I', 20, 0, 20);
  is(tripleZone(g1, g2, g3, 6, m).ok, false, 'три точки на прямой — не треугольник');

  // методики А/Б условия тройки не имеют
  is(tripleZone(A, B, C, 6, 'B').ok, false, 'для зоны Б условие тройки не применяется');

  // центр треугольника: при hx = 6 условие тройки выполнено -> защищён
  const rods = [A, B, C];
  const cv = coverageAt(0, 0, 6, rods, m);
  is(cv.covered, true, 'центр треугольника при hx = 6 защищён');
  is(cv.by, 'A–B–C', 'перекрыт именно тройкой, а не парой');

  // при hx = 18: ha = 2, Дmax = 16 < Д = 46.2, пары тоже разорваны
  is(coverageAt(0, 0, 18, rods, m).covered, false, 'центр при hx = 18 НЕ защищён');
}

