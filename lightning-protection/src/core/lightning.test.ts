let pass = 0, fail = 0;

function near(got: number, want: number, tol: number, label: string) {
  const ok = Math.abs(got - want) <= tol;
  if (ok) pass++; else fail++;
  console.log(
    `${ok ? '  ok  ' : ' FAIL '} ${label.padEnd(52)} got=${got.toFixed(3).padStart(9)}  want=${want.toFixed(3).padStart(9)}  tol=${tol}`,
  );
}
function is(got: unknown, want: unknown, label: string) {
  const ok = got === want;
  if (ok) pass++; else fail++;
  console.log(`${ok ? '  ok  ' : ' FAIL '} ${label.padEnd(52)} got=${String(got).padStart(9)}  want=${String(want)}`);
}

