using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Text;
using System.Threading;

namespace AutoPDF.Core.Licensing
{
    /// <summary>What this installation remembers about its registration (no secrets of the administrator).</summary>
    public sealed class LicenseRecord
    {
        public string InstallId { get; set; }
        public string ClientKey { get; set; }
        public string Name { get; set; }
        public string Email { get; set; }
        public string RequestId { get; set; }

        /// <summary>The status the server last reported.</summary>
        public RemoteStatus Status { get; set; }

        public DateTime? SubmittedUtc { get; set; }
        public DateTime? LastCheckUtc { get; set; }
        public DateTime? LastOnlineUtc { get; set; }

        /// <summary>The server asked not to be contacted before this time (throttling).</summary>
        public DateTime? NextCheckUtc { get; set; }

        /// <summary>Latest time this computer's clock has shown (to notice the clock being turned back).</summary>
        public DateTime? LastSeenUtc { get; set; }

        /// <summary>Server time − local time at the last successful check, in seconds.</summary>
        public long ClockOffsetSeconds { get; set; }

        /// <summary>Signing key learnt from the server over HTTPS (when no key is built in).</summary>
        public string ServerPublicKey { get; set; }

        public string Token { get; set; }
        public string Signature { get; set; }

        /// <summary>The last status the user has been told about (to notify about changes exactly once).</summary>
        public RemoteStatus NotifiedStatus { get; set; }

        public string LastMessage { get; set; }

        public bool HasRegistration => !string.IsNullOrEmpty(RequestId);
    }

    /// <summary>
    /// Stores <see cref="LicenseRecord"/> as "key=value" lines in %LOCALAPPDATA%\AutoPDFPro\license.txt
    /// (local, not roaming: the licence belongs to this computer). Written atomically; shared by every CAD
    /// host on this computer, so one approval covers AutoCAD and ZWCAD alike.
    /// </summary>
    public sealed class LicenseStore
    {
        public LicenseStore(string path)
        {
            FilePath = path ?? throw new ArgumentNullException(nameof(path));
        }

        public string FilePath { get; }

        public static string DefaultFilePath
        {
            get
            {
                string local = Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData);
                if (string.IsNullOrEmpty(local)) local = Path.GetTempPath();
                return Path.Combine(local, "AutoPDFPro", "license.txt");
            }
        }

        public LicenseRecord Load()
        {
            var r = new LicenseRecord();
            string text = ReadWithRetry();
            if (text == null) return r;
            Dictionary<string, string> v = Parse(text);

            r.InstallId = Get(v, "installId");
            r.ClientKey = Get(v, "clientKey");
            r.Name = Get(v, "name");
            r.Email = Get(v, "email");
            r.RequestId = Get(v, "requestId");
            LicenseToken.TryParseStatus(Get(v, "status"), out RemoteStatus status);
            r.Status = status;
            r.SubmittedUtc = Date(Get(v, "submittedUtc"));
            r.LastCheckUtc = Date(Get(v, "lastCheckUtc"));
            r.LastOnlineUtc = Date(Get(v, "lastOnlineUtc"));
            r.NextCheckUtc = Date(Get(v, "nextCheckUtc"));
            r.LastSeenUtc = Date(Get(v, "lastSeenUtc"));
            long.TryParse(Get(v, "clockOffset"), NumberStyles.Integer, CultureInfo.InvariantCulture, out long offset);
            r.ClockOffsetSeconds = offset;
            r.ServerPublicKey = Get(v, "serverPublicKey");
            r.Token = Get(v, "token");
            r.Signature = Get(v, "signature");
            LicenseToken.TryParseStatus(Get(v, "notifiedStatus"), out RemoteStatus notified);
            r.NotifiedStatus = notified;
            r.LastMessage = Get(v, "lastMessage");

            // A damaged identity is regenerated by the manager; never keep half-valid values.
            if (!InstallationIdentity.IsValidInstallId(r.InstallId) || !InstallationIdentity.IsValidClientKey(r.ClientKey))
            {
                return new LicenseRecord();
            }
            return r;
        }

        public void Save(LicenseRecord r)
        {
            if (r == null) throw new ArgumentNullException(nameof(r));
            var sb = new StringBuilder();
            sb.Append("# AutoPDF Pro licence state. Editing this file cannot grant a licence (it is signed by the server).\n");
            Put(sb, "installId", r.InstallId);
            Put(sb, "clientKey", r.ClientKey);
            Put(sb, "name", r.Name);
            Put(sb, "email", r.Email);
            Put(sb, "requestId", r.RequestId);
            Put(sb, "status", LicenseToken.StatusText(r.Status));
            Put(sb, "submittedUtc", Date(r.SubmittedUtc));
            Put(sb, "lastCheckUtc", Date(r.LastCheckUtc));
            Put(sb, "lastOnlineUtc", Date(r.LastOnlineUtc));
            Put(sb, "nextCheckUtc", Date(r.NextCheckUtc));
            Put(sb, "lastSeenUtc", Date(r.LastSeenUtc));
            Put(sb, "clockOffset", r.ClockOffsetSeconds.ToString(CultureInfo.InvariantCulture));
            Put(sb, "serverPublicKey", r.ServerPublicKey);
            Put(sb, "token", r.Token);
            Put(sb, "signature", r.Signature);
            Put(sb, "notifiedStatus", LicenseToken.StatusText(r.NotifiedStatus));
            Put(sb, "lastMessage", r.LastMessage);

            string dir = Path.GetDirectoryName(FilePath);
            if (!string.IsNullOrEmpty(dir)) Directory.CreateDirectory(dir);
            // A unique temp name: AutoCAD and ZWCAD may save at the same moment.
            string temp = FilePath + "." + Guid.NewGuid().ToString("N") + ".tmp";
            File.WriteAllText(temp, sb.ToString(), new UTF8Encoding(false));
            try
            {
                for (int attempt = 0; ; attempt++)
                {
                    try
                    {
                        if (File.Exists(FilePath)) File.Replace(temp, FilePath, null);
                        else File.Move(temp, FilePath);
                        return;
                    }
                    catch (IOException) when (attempt < 5)
                    {
                        Thread.Sleep(60); // the other process is reading or writing it right now
                    }
                }
            }
            finally
            {
                try { if (File.Exists(temp)) File.Delete(temp); } catch { /* best effort */ }
            }
        }

        /// <summary>
        /// The file's text, or null when it does not exist. A file that exists but cannot be read (another CAD
        /// process is replacing it) is retried and then reported as an exception — never mistaken for "no
        /// licence", which would create a new installation ID and lose the approval.
        /// </summary>
        private string ReadWithRetry()
        {
            for (int attempt = 0; ; attempt++)
            {
                try
                {
                    return File.ReadAllText(FilePath, Encoding.UTF8);
                }
                catch (FileNotFoundException)
                {
                    return null;
                }
                catch (DirectoryNotFoundException)
                {
                    return null;
                }
                catch (IOException) when (attempt < 5)
                {
                    Thread.Sleep(60);
                }
            }
        }

        internal static Dictionary<string, string> Parse(string text)
        {
            var v = new Dictionary<string, string>(StringComparer.Ordinal);
            foreach (string raw in (text ?? string.Empty).Replace("\r", string.Empty).Split('\n'))
            {
                if (raw.Length == 0 || raw[0] == '#') continue;
                int eq = raw.IndexOf('=');
                if (eq <= 0) continue;
                v[raw.Substring(0, eq)] = Uri.UnescapeDataString(raw.Substring(eq + 1));
            }
            return v;
        }

        private static void Put(StringBuilder sb, string key, string value)
        {
            if (string.IsNullOrEmpty(value)) return;
            sb.Append(key).Append('=').Append(Uri.EscapeDataString(value)).Append('\n');
        }

        private static string Get(Dictionary<string, string> v, string key) => v.TryGetValue(key, out string s) ? s : null;

        private static string Date(DateTime? d) =>
            d.HasValue ? d.Value.ToUniversalTime().ToString("yyyy-MM-ddTHH:mm:ssZ", CultureInfo.InvariantCulture) : null;

        private static DateTime? Date(string s) =>
            DateTime.TryParseExact(s, "yyyy-MM-ddTHH:mm:ssZ", CultureInfo.InvariantCulture,
                DateTimeStyles.AdjustToUniversal | DateTimeStyles.AssumeUniversal, out DateTime d)
                ? d
                : (DateTime?)null;
    }
}
